-- Compose a Spore view for the Canvas module host.
--
-- Canvas strips `load`, `require` and `package` from the sandbox, so there is no
-- module system to import `ui/lib/ui.lua` with yet. This pre-composes the
-- library and the view into the single file the host reads, which is exactly the
-- shape `components.require` will produce once it exists. Delete this tool when
-- the host resolves components itself.
--
--   lua tools/compose.lua "<Canvas runtime dir>/modules"

local out_dir = assert(arg[1], "usage: compose.lua <modules dir>")

local function read(path)
  local file = assert(io.open(path, "rb"), "missing " .. path)
  local text = file:read("*a")
  file:close()
  return text
end

local library = read("ui/lib/ui.lua")
local view = read("ui/editor.lua")

local composed = table.concat({
  "-- generated by tools/compose.lua from ui/lib/ui.lua + ui/editor.lua",
  "-- do not edit here; edit the sources and re-run the tool",
  "local ui = (function()",
  library,
  "end)()",
  view,
  "",
}, "\n")

-- The host bounds an adapter script at 32 KiB. A library plus a view crosses
-- that quickly, so drop comments and blank lines: the sources stay readable,
-- the artifact stays small.
local minified = composed:gsub("\n%s*%-%-[^\n]*", ""):gsub("\n%s*\n", "\n")

local path = out_dir .. "/spore-dev.lua"
local file = assert(io.open(path, "wb"), "cannot write " .. path)
file:write(minified)
file:close()
print(string.format("wrote %s (%d bytes, %d after minify)", path, #composed, #minified))
