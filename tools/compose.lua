-- Compose the search view into a single Canvas module.
--
-- Canvas strips load/require/package from the sandbox, so the view and the
-- mock snapshot are pre-composed. Delete this tool when Canvas resolves
-- components itself.
--
--   lua tools/compose.lua "<Canvas runtime modules dir>"

local out_dir = assert(arg[1], "usage: compose.lua <modules dir>")

local function read(path)
  local file = assert(io.open(path, "rb"), "missing " .. path)
  local text = file:read("*a")
  file:close()
  return text
end

-- Canvas caps a module source at 32 KiB. Strip comments and blank lines; the
-- authored files stay readable and the installed artifact stays bounded.
local function strip_comments(source)
  local out = {}
  local index, length = 1, #source
  local quote = nil
  while index <= length do
    local char = source:sub(index, index)
    if quote then
      out[#out + 1] = char
      if char == "\\" then
        index = index + 1
        out[#out + 1] = source:sub(index, index)
      elseif char == quote then
        quote = nil
      end
      index = index + 1
    elseif char == '"' or char == "'" then
      quote = char
      out[#out + 1] = char
      index = index + 1
    elseif char == "-" and source:sub(index + 1, index + 1) == "-" then
      while index <= length and source:sub(index, index) ~= "\n" do
        index = index + 1
      end
    else
      out[#out + 1] = char
      index = index + 1
    end
  end
  local lines = {}
  for raw in table.concat(out):gmatch("([^\n]*)\n?") do
    local line = raw:gsub("^%s+", ""):gsub("%s+$", "")
    if line ~= "" then lines[#lines + 1] = line end
  end
  return table.concat(lines, "\n")
end

local view = strip_comments(read("ui/search.lua"))
local snapshot = strip_comments(read(arg[2] or "examples/search_mock.lua"))

local composed = table.concat({
  "-- generated by tools/compose.lua from ui/search.lua + snapshot",
  "-- do not edit here; edit the sources and re-run the tool",
  "local snapshot = (function()",
  snapshot,
  "end)()",
  "local view = (function()",
  view,
  "end)()",
  "view.render(snapshot)",
  "",
}, "\n")

local path = out_dir .. "/spore-dev-search.lua"
local file = assert(io.open(path, "wb"), "cannot write " .. path)
file:write(composed)
file:close()

local manifest = table.concat({
  '{"schema_version":1,"id":"spore-dev-search","title":"Search",',
  '"inputs":[],"resources":[],',
  '"capabilities":{"write_scene":true,"read_inputs":[],"read_theme":true}}',
}, "")
local manifest_path = out_dir .. "/spore-dev-search.json"
file = assert(io.open(manifest_path, "wb"), "cannot write " .. manifest_path)
file:write(manifest)
file:close()
print(string.format("wrote %s (%d bytes) and %s", path, #composed, manifest_path))
